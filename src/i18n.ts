export function t(key: string, params?: Record<string, unknown>): string {
  let s = DICTS[lang][key] ?? DICTS.vi[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
  return s;
}
